function passage(
  id: string,
  level: PassageLevel,
  title: string,
  emoji: string,
  text: string,
  focus: string,
): ReadingPassage {
  return {
    id,
    level,
    title,
    text,
    emoji,
    wordCount: wordCount(text),
    focus,
    source: 'builtin',
  }
}

