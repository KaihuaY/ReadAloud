export function passageById(
  id: string,
  extra?: readonly ReadingPassage[],
): ReadingPassage | undefined {
  const all: readonly ReadingPassage[] = extra ? [...PASSAGES, ...SEED_BOOKS, ...extra] : [...PASSAGES, ...SEED_BOOKS]
  return all.find((p) => p.id === id)
}

export function passagesForLevel(level: PassageLevel): ReadingPassage[] {
  return PASSAGES.filter((p) => p.level === level)
}

export function levelInfo(level: PassageLevel): { level: PassageLevel; name: string; focus: string; hint: string } | undefined {
  return LEVELS.find((l) => l.level === level)
}
